use ex03_consistent_hash_ring::{Ring, ZeroVnodes, fnv1a, ring_hash};
use std::collections::HashMap;
use std::sync::mpsc;
use std::time::Duration;

/// Runs `f` on a thread and fails after 60 s instead of hanging the test run.
/// A correct run takes well under a second.
fn watchdog<T: Send + 'static>(f: impl FnOnce() -> T + Send + 'static) -> T {
    let (tx, rx) = mpsc::channel();
    std::thread::spawn(move || {
        let _ = tx.send(std::panic::catch_unwind(std::panic::AssertUnwindSafe(f)));
    });
    match rx.recv_timeout(Duration::from_secs(60)) {
        Ok(Ok(v)) => v,
        Ok(Err(p)) => std::panic::resume_unwind(p),
        Err(_) => panic!("test exceeded 60 s"),
    }
}

fn ring_of(vnodes: u32, n: usize) -> Ring {
    let mut r = Ring::new(vnodes).unwrap();
    for i in 0..n {
        assert!(r.add_node(&format!("node-{i}")));
    }
    r
}

fn keys(n: usize) -> Vec<String> {
    (0..n).map(|i| format!("key-{i}")).collect()
}

#[test]
fn provided_hashes_match_reference_values() {
    assert_eq!(fnv1a(b""), 0xcbf2_9ce4_8422_2325);
    assert_eq!(fnv1a(b"a"), 0xaf63_dc4c_8601_ec8c);
    assert_eq!(fnv1a(b"foobar"), 0x8594_4171_f739_67e8);
    assert_eq!(ring_hash(b"a"), 0x82a2_a958_a9be_ce5b);
}

#[test]
fn zero_vnodes_is_rejected() {
    assert_eq!(Ring::new(0).unwrap_err(), ZeroVnodes);
}

#[test]
fn empty_ring_returns_nothing() {
    watchdog(|| {
        let r = Ring::new(4).unwrap();
        assert_eq!(r.get(b"k"), None);
        assert!(r.get_replicas(b"k", 3).is_empty());
        assert_eq!((r.node_count(), r.vnode_count()), (0, 0));
    });
}

#[test]
fn add_and_remove_report_membership_changes() {
    watchdog(|| {
        let mut r = Ring::new(8).unwrap();
        assert!(r.add_node("a"));
        let vnodes = r.vnode_count();
        assert!(!r.add_node("a"));
        assert_eq!(r.vnode_count(), vnodes);
        assert_eq!(r.node_count(), 1);
        assert!(!r.remove_node("missing"));
        assert!(r.remove_node("a"));
        assert!(!r.remove_node("a"));
        assert_eq!((r.node_count(), r.vnode_count()), (0, 0));
    });
}

#[test]
fn single_node_owns_every_key() {
    watchdog(|| {
        let r = ring_of(4, 1);
        for k in keys(200) {
            assert_eq!(r.get(k.as_bytes()), Some("node-0"));
        }
    });
}

#[test]
fn vnode_count_is_nodes_times_vnodes_without_collisions() {
    watchdog(|| {
        let r = ring_of(160, 10);
        assert_eq!(r.node_count(), 10);
        assert_eq!(r.vnode_count(), 1600);
    });
}

/// Generated by the reference solution and re-derived with an independent Python
/// implementation of FNV-1a + fmix64 + a sorted-list ring.
const PINNED: [(&str, &str); 10] = [
    ("apple", "beta"),
    ("banana", "beta"),
    ("cherry", "beta"),
    ("date", "alpha"),
    ("elder", "gamma"),
    ("fig", "beta"),
    ("grape", "alpha"),
    ("honey", "gamma"),
    ("iris", "gamma"),
    ("mango", "gamma"),
];

#[test]
fn pinned_owners_for_three_nodes_four_vnodes() {
    watchdog(|| {
        let mut r = Ring::new(4).unwrap();
        for n in ["alpha", "beta", "gamma"] {
            r.add_node(n);
        }
        for (key, owner) in PINNED {
            assert_eq!(r.get(key.as_bytes()), Some(owner), "key {key}");
        }
    });
}

#[test]
fn key_above_highest_position_wraps_to_lowest() {
    watchdog(|| {
        // One vnode per node: positions are ring_hash("<name>#0").
        let names = ["alpha", "beta", "gamma"];
        let mut r = Ring::new(1).unwrap();
        for n in names {
            r.add_node(n);
        }
        let mut pos: Vec<(u64, &str)> = names
            .iter()
            .map(|n| (ring_hash(format!("{n}#0").as_bytes()), *n))
            .collect();
        pos.sort();
        let probe = |pred: &dyn Fn(u64) -> bool| {
            (0u64..)
                .map(|i| format!("probe-{i}"))
                .find(|k| pred(ring_hash(k.as_bytes())))
                .unwrap()
        };
        let above = probe(&|h| h > pos[2].0);
        assert_eq!(r.get(above.as_bytes()), Some(pos[0].1));
        let below = probe(&|h| h <= pos[0].0);
        assert_eq!(r.get(below.as_bytes()), Some(pos[0].1));
    });
}

#[test]
fn key_hashing_exactly_to_a_position_belongs_to_that_position() {
    watchdog(|| {
        // The key "<name>#0" hashes to the position of that node's only vnode.
        let r = ring_of(1, 5);
        for i in 0..5 {
            let name = format!("node-{i}");
            assert_eq!(r.get(format!("{name}#0").as_bytes()), Some(name.as_str()));
        }
    });
}

#[test]
fn removed_node_owns_nothing_and_others_keep_their_keys() {
    watchdog(|| {
        let mut r = ring_of(16, 5);
        let ks = keys(5_000);
        let before: Vec<String> = ks
            .iter()
            .map(|k| r.get(k.as_bytes()).unwrap().to_owned())
            .collect();
        assert!(r.remove_node("node-2"));
        for (k, old) in ks.iter().zip(&before) {
            let now = r.get(k.as_bytes()).unwrap();
            assert_ne!(now, "node-2");
            if old != "node-2" {
                assert_eq!(now, old, "key {k} moved though its owner stayed");
            }
        }
    });
}

#[test]
fn balance_ten_nodes_160_vnodes() {
    watchdog(|| {
        let r = ring_of(160, 10);
        let mut load: HashMap<&str, usize> = HashMap::new();
        for k in keys(100_000) {
            *load.entry(r.get(k.as_bytes()).unwrap()).or_default() += 1;
        }
        assert_eq!(load.len(), 10, "every node must own keys");
        let mean = 10_000.0;
        let max = *load.values().max().unwrap() as f64 / mean;
        let min = *load.values().min().unwrap() as f64 / mean;
        assert!(max <= 1.35, "max/mean = {max}");
        assert!(min >= 0.65, "min/mean = {min}");
    });
}

#[test]
fn adding_a_node_moves_keys_only_to_the_new_node() {
    watchdog(|| {
        let mut r = ring_of(160, 10);
        let ks = keys(100_000);
        let before: Vec<String> = ks
            .iter()
            .map(|k| r.get(k.as_bytes()).unwrap().to_owned())
            .collect();
        assert!(r.add_node("node-10"));
        let mut moved = 0usize;
        for (k, old) in ks.iter().zip(&before) {
            let new = r.get(k.as_bytes()).unwrap();
            if new != old {
                moved += 1;
                assert_eq!(new, "node-10", "key {k} moved between old nodes");
            }
        }
        let frac = moved as f64 / ks.len() as f64;
        assert!((0.05..=0.14).contains(&frac), "moved fraction = {frac}");
    });
}

#[test]
fn replicas_are_distinct_and_start_with_the_owner() {
    watchdog(|| {
        let r = ring_of(16, 5);
        for k in keys(2_000) {
            let reps = r.get_replicas(k.as_bytes(), 3);
            assert_eq!(reps.len(), 3);
            assert_eq!(Some(reps[0]), r.get(k.as_bytes()));
            let mut d = reps.clone();
            d.sort();
            d.dedup();
            assert_eq!(d.len(), 3, "duplicates in {reps:?}");
        }
    });
}

#[test]
fn replicas_are_capped_by_node_count_and_zero_is_empty() {
    watchdog(|| {
        let r = ring_of(16, 3);
        assert_eq!(r.get_replicas(b"k", 10).len(), 3);
        assert_eq!(r.get_replicas(b"k", 3).len(), 3);
        assert!(r.get_replicas(b"k", 0).is_empty());
    });
}
